import Foundation

enum AppLanguage: String, CaseIterable, Identifiable, Codable {
    case ko = "ko"
    case en = "en"
    case ja = "ja"
    case zhCN = "zh-CN"

    var id: String { rawValue }

    var nativeName: String {
        switch self {
        case .ko: return "한국어"
        case .en: return "English"
        case .ja: return "日本語"
        case .zhCN: return "简体中文"
        }
    }

    var shortCode: String {
        switch self {
        case .ko: return "KO"
        case .en: return "EN"
        case .ja: return "JA"
        case .zhCN: return "ZH"
        }
    }

    var defaultTargetLanguage: String {
        switch self {
        case .ko: return "한국어"
        case .en: return "English"
        case .ja: return "日本語"
        case .zhCN: return "中文(简体)"
        }
    }

    static func detectSystem() -> AppLanguage {
        let code = Locale.preferredLanguages.first?.lowercased() ?? "en"
        if code.hasPrefix("ko") { return .ko }
        if code.hasPrefix("ja") { return .ja }
        if code.hasPrefix("zh") { return .zhCN }
        return .en
    }
}

