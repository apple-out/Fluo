export function normalizeUiLanguage(raw?: string | null): UiLanguage {
  const clean = (raw ?? "").trim().toLowerCase().replace(/_/g, "-");
  if (clean === "en" || clean.startsWith("en-")) return "en";
  if (clean === "ja" || clean.startsWith("ja-")) return "ja";
  if (clean === "zh" || clean === "zh-cn" || clean.startsWith("zh-hans")) return "zh-CN";
  return "ko";
}

