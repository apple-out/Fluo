const dictionaries: Record<UiLanguage, Dict> = {
  ko,
  en,
  ja,
  "zh-CN": zhCN,
};

let currentLang = $state<UiLanguage>("ko");

export function getUiLang(): UiLanguage {
  return currentLang;
}

export function setUiLang(lang?: string | null): UiLanguage {
  const norm = normalizeUiLanguage(lang);
  currentLang = norm;
  if (typeof document !== "undefined" && document.documentElement) {
    document.documentElement.lang = norm;
  }
  return norm;
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  const dict = dictionaries[currentLang] ?? ko;
  let template: string = dict[key] ?? ko[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}
